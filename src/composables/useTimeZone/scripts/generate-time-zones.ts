import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { rawTimeZones, timeZonesNames, tzdbVersion } from '@vvo/tzdb';

/**
 * Generates `useTimeZone.constants.ts` from the installed `@vvo/tzdb`.
 *
 * Run manually after updating `@vvo/tzdb`:
 * ```sh
 * npm run generate:time-zones
 * ```
 */

const OUTPUT = resolve(import.meta.dirname, '../useTimeZone.constants.ts');

// Every name belongs to exactly one group, so the group's raw offset is the name's standard offset.
const offsets = new Map<string, number>(
  rawTimeZones.flatMap(({ group, rawOffsetInMinutes }) => {
    return group.map((name) => [name, rawOffsetInMinutes] as const);
  }),
);

const names = ['UTC', ...timeZonesNames];

const timeZones = names
  .map((name) => {
    const offset = name === 'UTC' ? 0 : offsets.get(name);

    if (offset === undefined) {
      throw new Error(`No offset found for "${name}"`);
    }

    return { name, offset };
  })
  // Plain string comparison keeps the order independent of the runtime locale.
  .sort((a, b) => a.offset - b.offset || (a.name < b.name ? -1 : 1));

const content = `// This file is generated by src/composables/useTimeZone/scripts/generate-time-zones.ts from @vvo/tzdb (tzdb ${tzdbVersion}).
// Do not edit manually, run \`npm run generate:time-zones\` instead.

import type { TimeZones } from './useTimeZone.types';

/**
 * All known IANA time zone names, including \`UTC\`.
 */
export const TIME_ZONE_NAMES = [
${names.map((name) => `  '${name}',`).join('\n')}
] as const;

/**
 * All known time zones, sorted by offset, then by name.
 */
export const TIME_ZONES: TimeZones = [
${timeZones.map(({ name, offset }) => `  { name: '${name}', offset: ${offset} },`).join('\n')}
];
`;

writeFileSync(OUTPUT, content);

console.log(`Generated ${timeZones.length} time zones into ${OUTPUT}`);
